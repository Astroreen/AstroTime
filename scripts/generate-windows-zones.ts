// Writes packages/core/src/windows-zones.ts from Unicode CLDR's windowsZones.xml
// (docs/plans/foundation.md#D32). Run it to move to a newer CLDR:
//
//   node scripts/generate-windows-zones.ts && vp fmt packages/core/src/windows-zones.ts
//
// Change CLDR_TAG (and CLDR_COMMIT, the commit the tag points at) to update.
import { writeFileSync } from "node:fs";

const CLDR_TAG = "release-49";
const CLDR_COMMIT = "96e54b273d2da4ec6fbad350ba19ff23fa24a588";
const SOURCE = "common/supplemental/windowsZones.xml";
const OUTPUT = new URL("../packages/core/src/windows-zones.ts", import.meta.url);

/**
 * The primary IANA zone of each Windows zone: the `territory="001"` rows, which
 * CLDR defines as the zone's golden mapping. A row's `type` may list several
 * IANA names for one territory; the first is the primary one.
 */
export function parseWindowsZones(xml: string): Record<string, string> {
  const zones: Record<string, string> = {};
  for (const [, attributes] of xml.matchAll(/<mapZone\s+([^>]*?)\/>/g)) {
    const attribute = (name: string) =>
      new RegExp(`\\b${name}="([^"]*)"`).exec(attributes ?? "")?.[1];
    if (attribute("territory") !== "001") continue;
    const windows = attribute("other");
    const iana = attribute("type")?.split(/\s+/)[0];
    if (!windows || !iana) throw new Error(`Unreadable mapZone: ${attributes}`);
    if (zones[windows] !== undefined && zones[windows] !== iana) {
      throw new Error(`${windows} maps to both ${zones[windows]} and ${iana}`);
    }
    zones[windows] = iana;
  }
  return zones;
}

export function renderModule(zones: Record<string, string>): string {
  const rows = Object.entries(zones)
    .toSorted(([a], [b]) => a.localeCompare(b, "en"))
    .map(([windows, iana]) => `  ${JSON.stringify(windows)}: ${JSON.stringify(iana)},`);
  return `// Generated by scripts/generate-windows-zones.ts from Unicode CLDR ${CLDR_TAG}
// (${CLDR_COMMIT}), ${SOURCE}.
// Do not edit by hand; regenerate with:
//   node scripts/generate-windows-zones.ts && vp fmt packages/core/src/windows-zones.ts

/** Windows time zone names (Outlook, Exchange) → the primary IANA zone (docs/plans/foundation.md#D32). */
export const WINDOWS_ZONES: Readonly<Record<string, string>> = {
${rows.join("\n")}
};
`;
}

async function main() {
  const url = `https://raw.githubusercontent.com/unicode-org/cldr/${CLDR_COMMIT}/${SOURCE}`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: ${response.status}`);
  const zones = parseWindowsZones(await response.text());
  writeFileSync(OUTPUT, renderModule(zones));
  console.log(`${Object.keys(zones).length} Windows zones from CLDR ${CLDR_TAG}`);
}

if (import.meta.main) await main();
