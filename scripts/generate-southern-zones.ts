// Writes packages/ui/src/pictures/southern-zones.ts, the time zones of the
// southern temperate zone, from the IANA tz database (docs/plans/design.md#D218):
// every zone whose location in `zone.tab` or `zone1970.tab` lies south of
// the Tropic of Capricorn, by its own location where it has one, else by
// the zone it links to (`backward`'s old
// names, and the links of the region files). Run it to move to a newer
// release:
//
//   node scripts/generate-southern-zones.ts && vp fmt packages/ui/src/pictures/southern-zones.ts
//
// Change TZ_TAG (and TZ_COMMIT, the commit the tag points at) to update.
import { writeFileSync } from "node:fs";

const TZ_TAG = "2026a";
const TZ_COMMIT = "dd6be6d1558163517ec55c652efac70842c3b4cc";
const TABLES = ["zone.tab", "zone1970.tab"];
const LINKS = [
  "backward",
  "africa",
  "antarctica",
  "asia",
  "australasia",
  "europe",
  "northamerica",
  "southamerica",
  "etcetera",
];
const OUTPUT = new URL("../packages/ui/src/pictures/southern-zones.ts", import.meta.url);

/**
 * The Tropic of Capricorn, 23°26′ south: the banners draw a temperate
 * zone's four seasons (snow, blossom, autumn leaves), which the tropics do
 * not have either side of the equator, so a zone there keeps the northern
 * months (Nairobi, Jakarta, Lima, Luanda alike).
 */
export const CAPRICORN = -(23 + 26 / 60);

/** A latitude in degrees from `zone.tab`'s ±DDMM or ±DDMMSS (the longitude after it). */
export function latitudeOf(coordinates: string): number {
  const match = /^([+-])(\d{2})(\d{2})(\d{2})?[+-]/.exec(coordinates);
  if (!match) throw new Error(`Unreadable coordinates: ${coordinates}`);
  const [, sign, degrees, minutes, seconds = "0"] = match;
  const value = Number(degrees) + Number(minutes) / 60 + Number(seconds) / 3600;
  return sign === "-" ? -value : value;
}

/** Each zone of a `zone.tab`-style table with its latitude. */
export function latitudesOf(table: string): [string, number][] {
  const zones: [string, number][] = [];
  for (const line of table.split("\n")) {
    if (line.startsWith("#") || line.trim() === "") continue;
    const [, coordinates, zone] = line.split("\t");
    if (!coordinates || !zone) throw new Error(`Unreadable row: ${line}`);
    zones.push([zone, latitudeOf(coordinates)]);
  }
  return zones;
}

/** Each `Link TARGET NAME` line of a tz source file, as [name, target]. */
export function linksOf(source: string): [string, string][] {
  const links: [string, string][] = [];
  for (const [, target, name] of source.matchAll(/^Link\s+(\S+)\s+(\S+)/gm)) {
    links.push([name!, target!]);
  }
  return links;
}

/**
 * The zones south of the Tropic of Capricorn: each by its own latitude
 * where a table gives it one (`Africa/Kampala` is a link to Nairobi in
 * `backward`, but `zone.tab` places it in Uganda), else by the zone it
 * links to, directly or through another link (`NZ`, `Brazil/East`).
 */
export function southernZones(
  latitudes: readonly [string, number][],
  links: readonly [string, string][],
): string[] {
  const own = new Map(latitudes);
  const target = new Map(links);
  const latitude = (zone: string, seen = new Set<string>()): number | undefined => {
    if (own.has(zone)) return own.get(zone);
    const next = target.get(zone);
    if (next === undefined || seen.has(zone)) return undefined;
    seen.add(zone);
    return latitude(next, seen);
  };
  const names = new Set([...own.keys(), ...target.keys()]);
  return [...names].filter((zone) => (latitude(zone) ?? 0) < CAPRICORN).toSorted();
}

export function renderModule(zones: readonly string[]): string {
  return `// Generated by scripts/generate-southern-zones.ts from the IANA tz database ${TZ_TAG}
// (${TZ_COMMIT}): the zones of ${TABLES.join(" and ")} south of the Tropic of Capricorn, and the names
// linked to them in ${LINKS.join(", ")} that have no location of their own. Do not edit by hand; regenerate with:
//   node scripts/generate-southern-zones.ts && vp fmt packages/ui/src/pictures/southern-zones.ts

/** Time zones south of the Tropic of Capricorn, by their tz database location (docs/plans/design.md#D218). */
export const SOUTHERN_ZONES: ReadonlySet<string> = new Set([
${zones.map((zone) => `  ${JSON.stringify(zone)},`).join("\n")}
]);
`;
}

async function main() {
  const get = async (path: string) => {
    const url = `https://raw.githubusercontent.com/eggert/tz/${TZ_COMMIT}/${path}`;
    const response = await fetch(url);
    if (!response.ok) throw new Error(`${url}: ${response.status}`);
    return response.text();
  };
  const latitudes = (await Promise.all(TABLES.map(get))).flatMap(latitudesOf);
  const links = (await Promise.all(LINKS.map(get))).flatMap(linksOf);
  const southern = southernZones(latitudes, links);
  writeFileSync(OUTPUT, renderModule(southern));
  console.log(`${southern.length} southern zones from tz ${TZ_TAG}`);
}

if (import.meta.main) await main();
