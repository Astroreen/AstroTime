// Writes packages/ui/src/pictures/southern-zones.ts, the time zones south of
// the equator, from the IANA tz database (docs/plans/design.md#D218): every
// zone whose location in `zone.tab` or `zone1970.tab` has a southern
// latitude, and every name the database links to one (`backward`'s old
// names, and the links of the region files). Run it to move to a newer
// release:
//
//   node scripts/generate-southern-zones.ts && vp fmt packages/ui/src/pictures/southern-zones.ts
//
// Change TZ_TAG (and TZ_COMMIT, the commit the tag points at) to update.
import { writeFileSync } from "node:fs";

const TZ_TAG = "2026a";
const TZ_COMMIT = "dd6be6d1558163517ec55c652efac70842c3b4cc";
const TABLES = ["zone.tab", "zone1970.tab"];
const LINKS = [
  "backward",
  "africa",
  "antarctica",
  "asia",
  "australasia",
  "europe",
  "northamerica",
  "southamerica",
  "etcetera",
];
const OUTPUT = new URL("../packages/ui/src/pictures/southern-zones.ts", import.meta.url);

/** The zones of a `zone.tab`-style table whose latitude is south of the equator. */
export function southernOf(table: string): string[] {
  const zones: string[] = [];
  for (const line of table.split("\n")) {
    if (line.startsWith("#") || line.trim() === "") continue;
    const [, coordinates, zone] = line.split("\t");
    if (!coordinates || !zone) throw new Error(`Unreadable row: ${line}`);
    // ±DDMM±DDDMM or ±DDMMSS±DDDMMSS: the sign of the latitude comes first.
    if (coordinates.startsWith("-")) zones.push(zone);
  }
  return zones;
}

/** Each `Link TARGET NAME` line of a tz source file, as [name, target]. */
export function linksOf(source: string): [string, string][] {
  const links: [string, string][] = [];
  for (const [, target, name] of source.matchAll(/^Link\s+(\S+)\s+(\S+)/gm)) {
    links.push([name!, target!]);
  }
  return links;
}

/** The southern zones with every name that links to one, directly or through another link. */
export function withLinks(zones: Iterable<string>, links: readonly [string, string][]): string[] {
  const southern = new Set(zones);
  for (let grew = true; grew;) {
    grew = false;
    for (const [name, target] of links) {
      if (southern.has(target) && !southern.has(name)) {
        southern.add(name);
        grew = true;
      }
    }
  }
  return [...southern].toSorted();
}

export function renderModule(zones: readonly string[]): string {
  return `// Generated by scripts/generate-southern-zones.ts from the IANA tz database ${TZ_TAG}
// (${TZ_COMMIT}): the zones of ${TABLES.join(" and ")} south of the equator, and the names
// linked to them in ${LINKS.join(", ")}. Do not edit by hand; regenerate with:
//   node scripts/generate-southern-zones.ts && vp fmt packages/ui/src/pictures/southern-zones.ts

/** Time zones south of the equator, by their tz database location (docs/plans/design.md#D218). */
export const SOUTHERN_ZONES: ReadonlySet<string> = new Set([
${zones.map((zone) => `  ${JSON.stringify(zone)},`).join("\n")}
]);
`;
}

async function main() {
  const get = async (path: string) => {
    const url = `https://raw.githubusercontent.com/eggert/tz/${TZ_COMMIT}/${path}`;
    const response = await fetch(url);
    if (!response.ok) throw new Error(`${url}: ${response.status}`);
    return response.text();
  };
  const zones = (await Promise.all(TABLES.map(get))).flatMap(southernOf);
  const links = (await Promise.all(LINKS.map(get))).flatMap(linksOf);
  const southern = withLinks(zones, links);
  writeFileSync(OUTPUT, renderModule(southern));
  console.log(`${southern.length} southern zones from tz ${TZ_TAG}`);
}

if (import.meta.main) await main();
